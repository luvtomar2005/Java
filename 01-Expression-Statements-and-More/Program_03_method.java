public class Program_03_method {
   public static void main(String[] args) {
        add(2 , 6);
        // here 2 and 6 are known as the arguments which are the actual values passed during the execution 
   }
   public static int add(int x , int y){
        return x + y;
        // x and y are the inputs which are being passed or known as parameters
   }
}


/* A method is a named block of reusable code that performs a specific task. It can accept
 input through parameters, execute some logic, and optionally 
return a value. Methods improve code reusability, readability, and maintainability.

IN java return statements return control to invoker of a method 

*/